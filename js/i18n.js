class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('ps_lang') || 'en';
  }

  setLanguage(lang) {
    if (TRANSLATIONS[lang]) {
      this.currentLang = lang;
      localStorage.setItem('ps_lang', lang);
      this.applyTranslations();
      if (window.onLanguageChange) window.onLanguageChange(lang);
    }
  }

  t(key) {
    return TRANSLATIONS[this.currentLang]?.[key] || TRANSLATIONS.en[key] || key;
  }

  getContentLila(lilaId, defaultLila) {
    if (this.currentLang !== 'en' && CONTENT_TRANSLATIONS[this.currentLang]?.lilas?.[lilaId]) {
      const trans = CONTENT_TRANSLATIONS[this.currentLang].lilas[lilaId];
      return {
        ...defaultLila,
        title: trans.title || defaultLila.title,
        period: trans.period || defaultLila.period,
        summary: trans.summary || defaultLila.summary,
        fullStory: trans.fullStory || defaultLila.fullStory,
        reflection: trans.reflection || defaultLila.reflection
      };
    }
    return defaultLila;
  }

  getContentTimeline(item) {
    if (this.currentLang !== 'en' && CONTENT_TRANSLATIONS[this.currentLang]?.timeline?.[item.id]) {
      const trans = CONTENT_TRANSLATIONS[this.currentLang].timeline[item.id];
      return {
        ...item,
        title: trans.title || item.title,
        summary: trans.summary || item.summary,
        details: trans.details || item.details
      };
    }
    return item;
  }

  getContentTeachings(defaultTeachings) {
    if (this.currentLang !== 'en' && CONTENT_TRANSLATIONS[this.currentLang]?.teachings) {
      const transList = CONTENT_TRANSLATIONS[this.currentLang].teachings;
      return defaultTeachings.map((t, i) => {
        const tr = transList[i];
        if (!tr) return t;
        return {
          ...t,
          title: tr.title || t.title,
          level: tr.level || t.level,
          subtitle: tr.subtitle || t.subtitle,
          description: tr.description || t.description,
          keyTakeaways: tr.keyTakeaways || t.keyTakeaways
        };
      });
    }
    return defaultTeachings;
  }

  getContentCenter(item) {
    if (this.currentLang !== 'en' && CONTENT_TRANSLATIONS[this.currentLang]?.centers?.[item.id]) {
      const trans = CONTENT_TRANSLATIONS[this.currentLang].centers[item.id];
      return {
        ...item,
        name: trans.name || item.name,
        city: trans.city || item.city,
        significance: trans.significance || item.significance
      };
    }
    return item;
  }

  applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (text) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = text;
        } else {
          el.innerHTML = text;
        }
      }
    });
  }
}

const i18n = new I18nManager();
